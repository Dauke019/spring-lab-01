-- lab 10: users and roles live in the database, passwords only as BCrypt hashes
-- (H2 here; on PostgreSQL "id bigserial primary key" is the same thing)
create table app_user (
    id            bigint generated by default as identity primary key,
    username      varchar(60)  not null unique,
    password_hash varchar(100) not null, -- BCrypt takes 60 characters
    enabled       boolean      not null default true
);

create table user_role (
    user_id bigint      not null references app_user (id),
    role    varchar(20) not null,
    primary key (user_id, role)
);

